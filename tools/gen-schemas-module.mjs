// Embeds schemas/*.schema.json and context/eps-v2.jsonld in src/schemas.mjs, so the module carries the exact
// published shapes and never reads or fetches them at run time (EPS R-P1). `--check` verifies the file is current.
//
//   node tools/gen-schemas-module.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const parts = [
  ['PROJECT_SCHEMA', 'schemas/edge-project-v2.schema.json'],
  ['RECORD_SCHEMA', 'schemas/artifact-record-v2.schema.json'],
  ['REVISION_SCHEMA', 'schemas/stage-revision-v2.schema.json'],
  ['REPORT_SCHEMA', 'schemas/project-report-v2.schema.json'],
  ['CONTEXT_DOCUMENT', 'context/eps-v2.jsonld'],
];

let out = '// Generated by tools/gen-schemas-module.mjs from schemas/ and context/. Do not edit.\n';
for (const [name, path] of parts) {
  out += `\n// ${path}\nexport const ${name} = ${JSON.stringify(read(path), null, 2)};\n`;
}

const target = join(root, 'src/schemas.mjs');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) {
    console.error('src/schemas.mjs is out of date: run node tools/gen-schemas-module.mjs');
    process.exit(1);
  }
  console.log('ok: src/schemas.mjs is current');
} else {
  writeFileSync(target, out);
  console.log('wrote src/schemas.mjs');
}
