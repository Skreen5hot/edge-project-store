// Generates the two browser pages as single, self-contained HTML files (M2-i, M2-h): the code of browser/*.mjs and
// the src/ modules they use is bundled into one inline script, so a page works when opened as a file (browsers do not
// load modules from file: pages), with no network and nothing installed. `--check` verifies both pages are current.
//
//   node tools/gen-pages.mjs [--check]
//
// The bundler handles only the forms this repository uses: `import { a, b as c } from './x.mjs'`, and `export` on
// a function, const, let or class declaration or as `export { a, b }`. Anything else stops it with an error. Each
// module runs in its own function scope, in dependency order, as it would as a module.

import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NAME = '[A-Za-z_$][\\w$]*';

/** The bundled code for `entry` (an absolute path), with `virtual` modules given as {id: source}. */
export function bundle(entry, virtual = {}) {
  const modules = [];
  const seen = new Set();
  const varOf = (id) => `__eps_${(id.startsWith('virtual:') ? id : relative(root, id)).replace(/[^\w]/g, '_')}`;

  function load(id) {
    if (seen.has(id)) return;
    seen.add(id);
    let body = virtual[id] ?? readFileSync(id, 'utf8');
    const deps = [];
    body = body.replace(new RegExp(`^import\\s*\\{([^}]*)\\}\\s*from\\s*'([^']+)';[ \\t]*$`, 'gm'), (_, names, spec) => {
      const dep = spec.startsWith('virtual:') ? spec : resolve(dirname(id), spec);
      if (!(dep in virtual) && !existsSync(dep)) throw new Error(`${id}: cannot find ${spec}`);
      deps.push(dep);
      const bindings = names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
        const m = s.match(new RegExp(`^(${NAME})(?:\\s+as\\s+(${NAME}))?$`));
        if (!m) throw new Error(`${id}: unsupported import binding ${s}`);
        return m[2] ? `${m[1]}: ${m[2]}` : m[1];
      });
      return `const { ${bindings.join(', ')} } = ${varOf(dep)};`;
    });
    if (/^\s*import[\s{*'"]/m.test(body)) throw new Error(`${id}: unsupported import form`);
    const exports = [];
    body = body.replace(new RegExp(`^export\\s+((?:async\\s+)?function\\*?|const|let|class)\\s+(${NAME})`, 'gm'), (_, kw, name) => {
      exports.push(name);
      return `${kw} ${name}`;
    });
    body = body.replace(/^export\s*\{([^}]*)\};?[ \t]*(\/\/.*)?$/gm, (_, names) => {
      for (const s of names.split(',').map((x) => x.trim()).filter(Boolean)) {
        const m = s.match(new RegExp(`^(${NAME})(?:\\s+as\\s+(${NAME}))?$`));
        if (!m) throw new Error(`${id}: unsupported export ${s}`);
        exports.push(m[2] ? `${m[2]}: ${m[1]}` : m[1]);
      }
      return '';
    });
    if (/^\s*export\s/m.test(body)) throw new Error(`${id}: unsupported export form`);
    for (const d of deps) load(d);
    modules.push({ id, body, exports });
  }

  load(entry);
  return modules.map((m) => [
    `// ---- ${m.id.startsWith('virtual:') ? m.id : relative(root, m.id).split('\\').join('/')}`,
    `const ${varOf(m.id)} = (() => {`,
    m.body.trimEnd(),
    `return { ${m.exports.join(', ')} };`,
    '})();',
  ].join('\n')).join('\n\n');
}

// The 25 examples, for the test page: each project's files (base64) and its expected report.
function examplesModule() {
  const dir = join(root, 'examples');
  const files = (base, sub = '') => readdirSync(join(base, sub)).sort().flatMap((n) => {
    const rel = sub ? `${sub}/${n}` : n;
    return statSync(join(base, rel)).isDirectory() ? files(base, rel) : [[rel, readFileSync(join(base, rel)).toString('base64')]];
  });
  const examples = readdirSync(dir).filter((n) => /^EX-\d\d-/.test(n)).sort().map((name) => ({
    name, files: files(join(dir, name, 'project')), expected: readFileSync(join(dir, name, 'expected.jsonld'), 'utf8'),
  }));
  return `export const EXAMPLES = ${JSON.stringify(examples)};\n`;
}

function page(template, entry, virtual) {
  const html = readFileSync(join(root, 'browser', 'templates', template), 'utf8');
  const code = bundle(join(root, 'browser', entry), virtual).replace(/<\/script/gi, '<\\/script');
  const marker = '<!-- EPS:SCRIPT -->';
  if (!html.includes(marker)) throw new Error(`${template} has no ${marker}`);
  return html.replace(marker, () => `<script type="module">\n// Generated by tools/gen-pages.mjs from browser/${entry} and the modules it imports. Do not edit.\n${code}\n</script>`);
}

const PAGES = [
  ['browser/eps-project.html', () => page('project.html', 'project-page.mjs', {})],
  ['browser/eps-browser-tests.html', () => page('tests.html', 'test-page.mjs', { 'virtual:examples': examplesModule() })],
];

const same = (a, b) => (process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b);
if (process.argv[1] && same(resolve(process.argv[1]), fileURLToPath(import.meta.url))) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [target, make] of PAGES) {
    const out = make();
    const file = join(root, target);
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== out) { console.error(`stale: ${target} (run node tools/gen-pages.mjs)`); stale++; }
    } else writeFileSync(file, out);
  }
  if (check && stale) process.exit(1);
  console.log(check ? `ok: ${PAGES.length} browser pages are current` : `wrote ${PAGES.map(([t]) => t).join(', ')}`);
}
